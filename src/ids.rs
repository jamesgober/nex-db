//! Identifiers: [`AccountId`] and [`Rid`].
//!
//! Both are 128-bit ULIDs (a millisecond timestamp and random bits), shown as
//! 26 Crockford base32 characters. They name records; they are not secrets.

use std::{fmt, str::FromStr};

use id_forge::ulid::Ulid;

use crate::error::Error;

macro_rules! ulid_id {
    ($(#[$doc:meta])* $name:ident, $what:literal) => {
        $(#[$doc])*
        #[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub struct $name([u8; 16]);

        impl $name {
            /// A new id at the current time.
            #[allow(dead_code)] // Each id is generated by one engine only.
            pub(crate) fn generate() -> Self {
                $name(*Ulid::new().as_bytes())
            }

            /// The id from its 16 bytes.
            #[must_use]
            pub const fn from_bytes(bytes: [u8; 16]) -> Self {
                $name(bytes)
            }

            /// The id's 16 bytes.
            #[must_use]
            pub const fn as_bytes(&self) -> &[u8; 16] {
                &self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::Display::fmt(&Ulid::from_bytes(&self.0), f)
            }
        }

        impl fmt::Debug for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, concat!(stringify!($name), "({})"), self)
            }
        }

        impl FromStr for $name {
            type Err = Error;

            fn from_str(s: &str) -> Result<Self, Error> {
                Ulid::parse_str(s)
                    .map(|u| $name(*u.as_bytes()))
                    .map_err(|_| Error::invalid($what, "not a 26-character ULID"))
            }
        }
    };
}

ulid_id!(
    /// An account id, assigned by the auth engine when an account is created.
    ///
    /// ```
    /// use nex_db::AccountId;
    /// let id: AccountId = "01ARZ3NDEKTSV4RRFFQ69G5FAV".parse()?;
    /// assert_eq!(id.to_string(), "01ARZ3NDEKTSV4RRFFQ69G5FAV");
    /// assert_eq!(AccountId::from_bytes(*id.as_bytes()), id);
    /// # Ok::<(), nex_db::Error>(())
    /// ```
    AccountId,
    "account id"
);

ulid_id!(
    /// A record id, assigned by the content engine when an entity is
    /// created. Never reused; independent of the entity's path.
    ///
    /// ```
    /// use nex_db::Rid;
    /// let rid: Rid = "01ARZ3NDEKTSV4RRFFQ69G5FAV".parse()?;
    /// assert_eq!(rid.to_string(), "01ARZ3NDEKTSV4RRFFQ69G5FAV");
    /// assert!("not-a-rid".parse::<Rid>().is_err());
    /// # Ok::<(), nex_db::Error>(())
    /// ```
    Rid,
    "record id"
);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_round_trips_through_text() {
        let id = AccountId::generate();
        let parsed: AccountId = id.to_string().parse().unwrap();
        assert_eq!(parsed, id);
    }

    #[test]
    fn test_generate_is_ordered_within_a_process() {
        let a = Rid::generate();
        let b = Rid::generate();
        assert!(b > a);
    }

    #[test]
    fn test_debug_names_the_type() {
        let id = Rid::from_bytes([0; 16]);
        assert_eq!(format!("{id:?}"), "Rid(00000000000000000000000000)");
    }
}
